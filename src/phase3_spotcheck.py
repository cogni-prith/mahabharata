"""Phase 3 gate: the spot-check the gate asks for, on the Gita and one embedded tale.

The gate is "nesting depth reconstructs for the known frame levels, spot-check
the Gita and one embedded tale". The depth distribution was reported; the two
spot-checks were not, so this closes that gap.

The Gita is Bhishma Parva chapters 25 to 42 in the BORI numbering. Its frame is
known independently of this corpus: Sauti recites to Shaunaka, Vaishampayana
recites to Janamejaya inside that, Sanjaya reports to Dhritarashtra inside that,
and Krishna speaks to Arjuna inside that. Four levels, so the span should carry
Sanjaya, Arjuna and a nesting of at least three levels.

Krishna is not named by the text in his own speech frames there. Debroy prints
them "The lord said", twelve times in this span, so the telling is emitted with
`narratorUnresolved` and no referent is chosen. That the innermost narrator of the
Gita is unresolved is a fact about the translation's frame formatting, not a gap
to be filled by inference.

The embedded tale is Nala and Damayanti, Aranyaka 50 to 78, narrated by
Brihadashva to Yudhishthira inside the Vaishampayana frame. Its narrator should
be Brihadashva and its depth should sit one below the frame it is told in.

The test is that the recovered narrators and depths match those known frames. It
is written as asserts so it fails loudly rather than producing a report nobody
reads.
"""
import pandas as pd

GITA = ("06_Bhishma", 25, 42)
NALA = ("03_Aranyaka", 50, 78)


def span(t, parva, lo, hi):
    return t[(t.parva == parva) & (t.adhyaya_ordinal >= lo) & (t.adhyaya_ordinal <= hi)]


def main():
    t = pd.read_parquet("build/tellings.parquet")
    L = ["# Phase 3 spot-check, the Gita and one embedded tale", "",
         "Generated by `src/phase3_spotcheck.py`. The frames below are known",
         "independently of this corpus, so they are a real check and not a restatement",
         "of the extractor's own output.", ""]

    g = span(t, *GITA)
    gn = g.narrator.value_counts()
    L += ["## Bhagavad Gita, Bhishma Parva chapters %d to %d" % GITA[1:], "",
          "Expected frame: Sauti, then Vaishampayana, then Sanjaya, then Krishna.", "",
          "- Tellings in the span: %d, depths %s" % (len(g), sorted(g.depth.unique())),
          "- Narrators: " + ", ".join("%s %d" % (k, v) for k, v in gn.head(8).items()), ""]
    deep = g[g.depth == g.depth.max()]
    L += ["- Deepest level (%d): %s" % (g.depth.max(),
          ", ".join("%s %d" % (k, v) for k, v in deep.narrator.value_counts().head(5).items())), ""]
    unres = g[g.narrator.isna()]
    L += ["- Unresolved titular narrators: %d, surfaces %s"
          % (len(unres), ", ".join("%s %d" % (k, v)
                                   for k, v in unres.narrator_surface.value_counts().items())), ""]
    assert "Sanjaya" in gn.index, "Sanjaya is not a narrator in the Gita span"
    assert "Arjuna" in gn.index, "Arjuna is not a narrator in the Gita span"
    assert len(unres), "the Gita span has no unresolved titular narrator, so " \
                       "Krishna's frames are being dropped again"
    assert g.depth.max() >= 2, "the Gita span does not nest at least three levels"

    n = span(t, *NALA)
    nn = n.narrator.value_counts()
    L += ["## Nala and Damayanti, Aranyaka chapters %d to %d" % NALA[1:], "",
          "Expected narrator: Brihadashva, to Yudhishthira, inside the Vaishampayana frame.", "",
          "- Tellings in the span: %d, depths %s" % (len(n), sorted(n.depth.unique())),
          "- Narrators: " + ", ".join("%s %d" % (k, v) for k, v in nn.head(8).items()), ""]
    assert "Brihadashva" in nn.index, "Brihadashva does not narrate the Nala span"
    assert nn["Brihadashva"] >= 10, "Brihadashva narrates only %d tellings there" % nn["Brihadashva"]
    assert n.depth.max() >= 1, "the Nala span does not nest"

    L += ["## Verdict", "",
          "Both frames reconstruct. The Gita span carries Sanjaya and Arjuna, nests to",
          "depth %d, and holds %d tellings whose narrator the text names only by title"
          % (g.depth.max(), len(unres)),
          "and which are therefore left unresolved. Brihadashva narrates %d tellings in"
          % nn["Brihadashva"],
          "the Nala span, nesting to depth %d." % n.depth.max(), "",
          "What this does not check: whether a narrator is attached to the right",
          "sentence within a chapter. The citation unit is the chapter, so the check",
          "cannot go finer than the citation.", ""]
    open("build/phase3_spotcheck.md", "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("Gita: %d tellings, max depth %d, Sanjaya %d. Nala: %d tellings, Brihadashva %d"
          % (len(g), g.depth.max(), gn.get("Sanjaya", 0), len(n), nn["Brihadashva"]))


if __name__ == "__main__":
    main()
