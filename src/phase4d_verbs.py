"""Measure which verbs could carry a predicate, before any predicate is added.

The predicate set is expanded on evidence rather than on what an ontology can
express. This counts, over the whole corpus, every clause in which a verb has
both a subject and an object that resolve to a person by the means Phase 4
already has: a directly read name, a third person coreference resolution, or a
noun-phrase link against the graph. The count for a verb is therefore the number
of triples a predicate built on it would actually yield, not the number of times
the verb occurs.

Non-assertive clauses are excluded on the same test the extractor uses, so the
numbers are what would survive.
"""
import collections, sys
import pandas as pd
import spacy

import nplink
from phase4_relations import (load_entities, load_coref, load_depth, ent_of,
                              non_assertive, usable, KILL)


def main():
    limit = int(sys.argv[1]) if len(sys.argv) > 1 else 0
    persons, places, df = load_entities()
    coref_all = load_coref()
    sents = df.drop_duplicates(subset=["parva", "sent_id"])[
        ["parva", "sent_id", "sentence"]].sort_values(["parva", "sent_id"])
    if limit:
        sents = sents.head(limit)
    rel = pd.read_parquet("build/relations.parquet")
    table = nplink.build_table(rel)
    nlp = spacy.load("en_core_web_sm", disable=["ner"])

    rows = sents.to_dict("records")
    pairs = collections.Counter()     # verb -> clauses with two person arguments
    subjects = collections.Counter()  # verb -> distinct subject-object pairs
    seen = collections.defaultdict(set)
    prov = collections.Counter()
    for r, doc in zip(rows, nlp.pipe([r["sentence"] for r in rows],
                                     batch_size=256, n_process=1)):
        coref = coref_all.get((r["parva"], int(r["sent_id"])))
        for tok in doc:
            if tok.pos_ != "VERB" or non_assertive(tok):
                continue
            subs = [c for c in tok.children if c.dep_ in ("nsubj", "nsubjpass")]
            objs = [c for c in tok.children if c.dep_ in ("dobj", "obj")]
            objs += [g for c in tok.children if c.dep_ == "agent"
                     for g in c.children if g.dep_ == "pobj"]
            for s_ in subs:
                for o_ in objs:
                    if not (usable(s_) and usable(o_)):
                        continue
                    sn, sk, sp = ent_of(s_, persons, places, coref, table)
                    on, ok, op = ent_of(o_, persons, places, coref, table)
                    if not (sn and on and sk == ok == "person" and sn != on):
                        continue
                    lemma = tok.lemma_.lower()
                    pairs[lemma] += 1
                    seen[lemma].add((sn, on))
                    prov["direct" if sp is None and op is None else "derived"] += 1
    for k in pairs:
        subjects[k] = len(seen[k])

    L = ["# Candidate verbs for predicate expansion", "",
         "Generated by `src/phase4d_verbs.py` over all %d sentences." % len(sents),
         "A row counts clauses where the verb has a subject and an object that both",
         "resolve to a person, and the clause is assertive. That is the number of",
         "triple instances a predicate built on this verb would yield.", "",
         "- Total such clauses: %d" % sum(pairs.values()),
         "- Distinct verbs: %d" % len(pairs),
         "- Both arguments read directly: %d; at least one derived: %d"
         % (prov["direct"], prov["derived"]), "",
         "| verb | clauses | distinct pairs |", "|---|---|---|"]
    for v, n in pairs.most_common(80):
        L.append("| %s | %d | %d |" % (v, n, subjects[v]))
    open("build/phase4d_verbs.md", "w").write("\n".join(L) + "\n")
    print("\n".join(L[:14]))
    print("\n".join(L[14:44]))


if __name__ == "__main__":
    main()
