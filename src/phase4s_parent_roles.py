"""Phase 4s. Mother or father, for parents the graph already holds.

`bornTo` is a generic parent: the extraction never guessed which. GLiREL
(Phase 4r) labels pairs "is the mother of" or "is the father of", and while a
single row cannot be trusted for direction, the count over the whole corpus for
one person mostly can: Kunti 157 mother to 23 father, Pandu 11 to 160.

This labels only people who already appear as the object of a reviewed bornTo
fact, and only where the count is lopsided. Everyone else stays a plain parent.
Nothing in the graph is changed; the labels go to build/parent_roles.csv, which
the chat layer reads if it exists. Delete that file to undo.

Counting, per sentence and per pair: GLiREL gives most pairs the same label in
both orders, and the higher-scoring order puts the parent first about 85% of
the time on pairs the graph already knew. So only that order's head is counted
as the parent. Names are folded through the Phase 2b links exactly as Phase 4f
folds relation endpoints, so the counts land on the graph's own names.

Run: python src/phase4s_parent_roles.py [--ratio 3] [--min 10]
"""
import argparse
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

GLIREL = "build/glirel_relations.parquet"
GRAPH = "build/reviewed_relations.parquet"
LINKS = "build/er/mention_links.csv"
OUT = "build/parent_roles.csv"
REPORT = "build/parent_roles.md"
ROLE = {"is the mother of": "mother", "is the father of": "father"}


def fold_names(g):
    """GLiREL's names through the Phase 2b links, as Phase 4f folds relations."""
    if not os.path.exists(LINKS):
        return g
    from phase2b_confidence import endpoint_map
    m = endpoint_map(pd.read_csv(LINKS, dtype={"parva": str}))
    ch = [None if pd.isna(a) else "%s/%d" % (p, int(a)) for p, a in zip(g.parva, g.adhyaya_ordinal)]
    return g.assign(
        head=[m(n, p, int(s), c) for n, p, s, c in zip(g["head"], g.parva, g.sent_id, ch)],
        tail=[m(n, p, int(s), c) for n, p, s, c in zip(g["tail"], g.parva, g.sent_id, ch)])


def parent_sightings(g):
    """One row per (sentence, pair, label): the higher-scoring order, head as parent."""
    g = g[g.label.isin(ROLE)].copy()
    g = fold_names(g)
    g = g[g["head"] != g["tail"]]
    g["pair"] = [frozenset(x) for x in zip(g["head"], g["tail"])]
    g = g.sort_values("score", ascending=False).drop_duplicates(["parva", "sent_id", "pair", "label"])
    return g.assign(parent=g["head"], role=g.label.map(ROLE))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--ratio", type=float, default=3.0, help="the winning role must outnumber the other this many times")
    ap.add_argument("--min", type=int, default=10, help="sightings needed before a role is given")
    args = ap.parse_args()
    if not os.path.exists(GLIREL):
        raise SystemExit("%s does not exist. Run Phase 4r (GLiREL) first." % GLIREL)

    rel = pd.read_parquet(GRAPH if os.path.exists(GRAPH) else "build/relations.parquet")
    parents = set(rel.loc[rel.predicate == "bornTo", "object"])
    seen = parent_sightings(pd.read_parquet(GLIREL))
    counts = (seen[seen.parent.isin(parents)].groupby(["parent", "role"]).size()
              .unstack(fill_value=0).reindex(columns=["mother", "father"], fill_value=0))
    counts = counts.reindex(sorted(parents), fill_value=0)

    def decide(r):
        n = r.mother + r.father
        if n < args.min:
            return "parent"
        if r.mother >= args.ratio * max(r.father, 1) and r.mother > r.father:
            return "mother"
        if r.father >= args.ratio * max(r.mother, 1) and r.father > r.mother:
            return "father"
        return "parent"

    out = counts.assign(sightings=counts.mother + counts.father)
    out["role"] = out.apply(decide, axis=1)
    out = out.rename(columns={"mother": "mother_count", "father": "father_count"})
    out.index.name = "parent"
    out = out.reset_index()[["parent", "role", "mother_count", "father_count", "sightings"]]
    out.to_csv(OUT, index=False)

    decided = out[out.role != "parent"].sort_values("sightings", ascending=False)
    close = out[(out.role == "parent") & (out.sightings >= args.min)].sort_values("sightings", ascending=False)
    lines = ["# Phase 4s. Mother or father, from GLiREL counts", "",
             "Generated by `src/phase4s_parent_roles.py`. Labels only parents already in the "
             "reviewed graph; the graph itself is unchanged. Rule: a role needs %d or more "
             "sightings and must outnumber the other %.0f to 1. Delete `%s` to undo."
             % (args.min, args.ratio, OUT), "",
             "- Parents in the graph: %d" % len(out),
             "- Given a role: %d (%d mother, %d father)" % (len(decided), (decided.role == "mother").sum(),
                                                          (decided.role == "father").sum()),
             "- Enough sightings but too close to call, left as parent: %d" % len(close),
             "- Too few sightings, left as parent: %d" % (out.sightings < args.min).sum(), "",
             "Counts are GLiREL output, not judged. The rule is a guard, not a measured precision.", "",
             "## Given a role", "", "| parent | role | mother | father |", "|---|---|---|---|"]
    lines += ["| %s | %s | %d | %d |" % (r.parent, r.role, r.mother_count, r.father_count)
              for r in decided.itertuples()]
    lines += ["", "## Too close to call", "", "| parent | mother | father |", "|---|---|---|"]
    lines += ["| %s | %d | %d |" % (r.parent, r.mother_count, r.father_count) for r in close.itertuples()]
    open(REPORT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines[:12]))


if __name__ == "__main__":
    main()
