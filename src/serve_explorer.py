"""Loopback-only read-only explorer service. No corpus writes.

One endpoint calls out. `/api/chat` sends a question and its retrieved context
to a third-party model when the service was started with `GROQ_API_KEY` set,
which is D27. Without the key the endpoint still answers, returning the
retrieved evidence and nothing generated. Every other endpoint is local and
stays local, and the key is never sent to the browser.
"""
import argparse
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import json
import mimetypes
import os
from pathlib import Path
from urllib.parse import parse_qs, unquote, urlsplit

from rdflib import Graph, OWL, RDF, RDFS
from chat import MODEL, Retriever, generate, retrieve
from semantic_index import ROOT, MBH
from semantic_search import SearchIndex, validate_query

MAX_HISTORY = 6
MAX_TURN = 4000


def clean_history(raw):
    """Only the shape the prompt expects, and only the last few turns.

    The browser supplies this, so it is untrusted input that ends up inside a
    prompt. Anything that is not a plain user or assistant string is dropped
    rather than repaired.
    """
    if raw is None:
        return []
    if not isinstance(raw, list):
        raise ValueError('History must be a list of turns')
    turns = []
    for t in raw[-MAX_HISTORY:]:
        if not isinstance(t, dict) or set(t) != {'role', 'content'}:
            raise ValueError('Each turn needs a role and content')
        if t['role'] not in {'user', 'assistant'} or not isinstance(t['content'], str):
            raise ValueError('Unknown turn role')
        if len(t['content']) > MAX_TURN:
            raise ValueError('A turn exceeds %d characters' % MAX_TURN)
        turns.append({'role': t['role'], 'content': t['content']})
    return turns


def static_path(root,url):
    path=(Path(root)/unquote(url).lstrip('/')).resolve()
    if not path.is_relative_to(Path(root).resolve()) or any(p.startswith('.') for p in Path(unquote(url)).parts):
        raise ValueError('Path is outside the viewer')
    if path.suffix not in {'.html','.js','.css','.json','.md','.txt','.ttl','.trig','.png','.svg','.ico'}:
        raise ValueError('File type is not served')
    return path


def make_server(index,port=8765,key=None,retriever=None):
    schema=Graph().parse(index.root/'ontology/mahabharata.ttl')
    retriever=retriever or Retriever(index.root,index=index)
    chat_config={'enabled':True,'generated':bool(key),'model':MODEL if key else None,
                 'remote':bool(key),
                 'notice':('Answers are generated by a third-party model from the retrieved '
                           'context below each one. Retrieval is cited; generation is not '
                           'independently verified.') if key else
                          ('No API key is configured, so nothing is sent anywhere and nothing '
                           'is generated. This is the evidence an answer would be built from.')}
    classes=[{'id':str(c).rsplit('/',1)[-1],'label':str(schema.value(c,RDFS.label) or str(c).rsplit('/',1)[-1]),
              'description':str(schema.value(c,RDFS.comment) or ''),
              'parents':[str(o).rsplit('/',1)[-1] for o in schema.objects(c,RDFS.subClassOf)]}
             for c in schema.subjects(RDF.type,OWL.Class)]

    class Handler(BaseHTTPRequestHandler):
        def send(self,status,payload,content_type='application/json; charset=utf-8'):
            body=payload if isinstance(payload,bytes) else json.dumps(payload,ensure_ascii=True,allow_nan=False).encode()
            self.send_response(status); self.send_header('Content-Type',content_type)
            self.send_header('Content-Length',str(len(body))); self.send_header('Cache-Control','no-store')
            self.send_header('X-Content-Type-Options','nosniff'); self.send_header('Referrer-Policy','no-referrer')
            self.send_header('Content-Security-Policy',"default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; connect-src 'self'; object-src 'none'; frame-ancestors 'none'; base-uri 'self'")
            self.end_headers(); self.wfile.write(body)

        def local_request(self):
            host=self.headers.get('Host','')
            valid={f'127.0.0.1:{self.server.server_port}',f'localhost:{self.server.server_port}'}
            origin=self.headers.get('Origin')
            return host in valid and (origin is None or origin=='http://'+host)

        def do_GET(self):
            if not self.local_request(): return self.send(403,{'error':'Loopback requests only'})
            url=urlsplit(self.path); q=parse_qs(url.query)
            try:
                if url.path=='/api/status':
                    return self.send(200,{**{k:v for k,v in index.manifest.items() if k not in {'node_ids','passage_ids'}},
                                          'chat':chat_config})
                if url.path=='/api/map': return self.send(200,index.map)
                if url.path=='/api/schema': return self.send(200,{'classes':classes,'candidate_types':True})
                if url.path=='/api/node': return self.send(200,index.node(q.get('id',[''])[0]))
                if url.path=='/api/passage': return self.send(200,index.passage(q.get('id',[''])[0]))
                if url.path.startswith('/api/'): return self.send(404,{'error':'Unknown endpoint'})
                path=static_path(index.root/'out','/index.html' if url.path=='/' else url.path)
                if not path.is_file(): return self.send(404,{'error':'File not found'})
                return self.send(200,path.read_bytes(),mimetypes.guess_type(path)[0] or 'application/octet-stream')
            except KeyError as ex: self.send(404,{'error':str(ex)})
            except ValueError as ex: self.send(400,{'error':str(ex)})
            except Exception as ex:
                self.log_error('Request failed: %s',type(ex).__name__)
                self.send(500,{'error':'Local index error. Check the service terminal.'})

        def do_POST(self):
            if not self.local_request(): return self.send(403,{'error':'Loopback requests only'})
            if self.path not in {'/api/search','/api/chat'}: return self.send(404,{'error':'Unknown endpoint'})
            try:
                size=int(self.headers.get('Content-Length','0'))
                if not 1<=size<=16384: return self.send(413,{'error':'Request body must be 1 to 16384 bytes'})
                if self.headers.get_content_type()!='application/json': return self.send(415,{'error':'JSON required'})
                data=json.loads(self.rfile.read(size))
                if not isinstance(data,dict): raise ValueError('Invalid request body')
                if self.path=='/api/chat':
                    if set(data)-{'query','history'}: raise ValueError('Invalid chat fields')
                    return self.send(200,self.chat(data))
                if set(data)-{'query','kind','limit'}: raise ValueError('Invalid search fields')
                self.send(200,index.search(data.get('query'),data.get('kind'),data.get('limit',12)))
            except (ValueError,TypeError) as ex: self.send(400,{'error':str(ex)})
            except RuntimeError as ex: self.send(502,{'error':str(ex)})
            except Exception as ex:
                self.log_error('Request failed: %s',type(ex).__name__)
                self.send(500,{'error':'Local request failed. Check the service terminal.'})

        def chat(self,data):
            history=clean_history(data.get('history'))
            found=retrieve(retriever,validate_query(data.get('query')))
            found.update(chat_config)
            # The context is returned whether or not a model saw it, so the
            # page can show what an answer rests on, or would have rested on.
            found['answer']=generate(found['query'],found['context'],history,key) if key else None
            return found

        def setup(self):
            super().setup(); self.connection.settimeout(20)

    server=ThreadingHTTPServer(('127.0.0.1',port),Handler)
    server.daemon_threads=True
    return server


if __name__=='__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--port',type=int,default=8765)
    args=parser.parse_args(); index=SearchIndex()
    key=os.environ.get('GROQ_API_KEY')
    server=make_server(index,args.port,key)
    print(f'Local explorer: http://127.0.0.1:{server.server_port}/index.html',flush=True)
    print('Ask mode: '+('generating answers remotely, D27' if key else
                        'GROQ_API_KEY unset, retrieval only, nothing leaves this machine'),flush=True)
    try: server.serve_forever()
    except KeyboardInterrupt: pass
    finally: server.server_close()
